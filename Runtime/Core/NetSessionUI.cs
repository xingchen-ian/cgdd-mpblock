using System.Text;
using Unity.Netcode;
using UnityEngine;
using UnityEngine.UI;

namespace MPBlocks.Core
{
    /// <summary>
    /// The session screen: host a game, join one by address, leave, and see who is here.
    ///
    /// It also surfaces the reason a connection was refused ("server full",
    /// "wrong game"). Without that, a rejected join looks like the game is simply broken,
    /// which is the single most common way students lose an hour.
    ///
    /// Every button also exists as a public method, so a design can drive the session
    /// from code instead of the UI.
    /// </summary>
    [DisallowMultipleComponent]
    public sealed class NetSessionUI : MonoBehaviour
    {
        [Header("MPBlocks")]
        [Tooltip("NetBootstrap to drive; when empty the one in the scene is found automatically, so dragging it in is usually unnecessary. Without one, Host and Join only log an [MP] warning.")]
        [SerializeField] private NetBootstrap bootstrap;

        [Header("References")]
        [Tooltip("Shows the session state: not connected, connecting, hosting with port and player count, or the local client id. Wired by the scene generator, so manual dragging is normally unnecessary.")]
        [SerializeField] private Text statusText;
        [Tooltip("Lists the connected players line by line and marks (you) and [host]. Wired by the scene generator, so manual dragging is normally unnecessary; leaving it empty just hides the list.")]
        [SerializeField] private Text playerListText;
        [Tooltip("Shows why a connection was refused, for example server full or wrong game. Wired by the scene generator, so manual dragging is normally unnecessary.")]
        [SerializeField] private Text reasonText;
        [Tooltip("Server IP typed in before joining; when empty the NetConfig defaultAddress is used. Wired by the scene generator, so manual dragging is normally unnecessary.")]
        [SerializeField] private InputField nameInput;

        [SerializeField] private InputField addressInput;
        [Tooltip("Calls NetBootstrap.StartServer() to host or start a dedicated server, and greys out while a session is running. Wired by the scene generator, so manual dragging is normally unnecessary.")]
        [SerializeField] private Button hostButton;
        [Tooltip("Calls NetBootstrap.StartClient() with the address from the input field, and greys out while a session is running. Wired by the scene generator, so manual dragging is normally unnecessary.")]
        [SerializeField] private Button joinButton;
        [Tooltip("Shuts the current session down and returns to not connected; greyed out when nothing is running. Wired by the scene generator, so manual dragging is normally unnecessary.")]
        [SerializeField] private Button leaveButton;

        private readonly StringBuilder _builder = new StringBuilder(256);
        private string _lastReason;

        private NetworkManager Manager => bootstrap != null ? bootstrap.Manager : NetworkManager.Singleton;

        private void Awake()
        {
            if (bootstrap == null)
            {
                bootstrap = FindObjectOfType<NetBootstrap>();
            }

            // Wired in code rather than as persistent Inspector listeners, so the
            // component works whether it was placed by hand or generated by the editor.
            Wire(hostButton, Host);
            Wire(joinButton, Join);
            Wire(leaveButton, Leave);

            // Show the name saved on this machine, so nobody retypes it every session.
            if (nameInput != null && string.IsNullOrEmpty(nameInput.text))
            {
                nameInput.text = LocalPlayerName.Get();
            }
        }

        private static void Wire(Button button, UnityEngine.Events.UnityAction action)
        {
            if (button == null) return;
            button.onClick.RemoveAllListeners();
            button.onClick.AddListener(action);
        }

        private void Update()
        {
            Refresh();
        }

        // ---- actions (also callable from code or the Inspector) ----

        public void Host()
        {
            if (bootstrap == null)
            {
                MPLog.Warn(MPEvent.ConfigError, ("reason", "NetSessionUI has no NetBootstrap"));
                return;
            }

            RememberName();
            ClearReason();
            bootstrap.StartServer();
        }

        public void Join()
        {
            if (bootstrap == null)
            {
                MPLog.Warn(MPEvent.ConfigError, ("reason", "NetSessionUI has no NetBootstrap"));
                return;
            }

            var address = Address;
            RememberName();
            ClearReason();
            bootstrap.StartClient(address);
        }

        public void Leave()
        {
            var manager = Manager;
            if (manager == null || !manager.IsListening) return;

            MPLog.Info("SESSION_LEAVE");
            manager.Shutdown();
        }

        /// <summary>The name typed on this screen, saved so it survives a restart.</summary>
        public string PlayerName => nameInput != null ? LocalPlayerName.Sanitize(nameInput.text) : LocalPlayerName.Get();

        private void RememberName()
        {
            if (nameInput == null) return;

            var typed = LocalPlayerName.Sanitize(nameInput.text);
            if (string.IsNullOrEmpty(typed)) return;

            LocalPlayerName.Set(typed);
            MPLog.Info("NAME_REMEMBERED", ("name", typed));
        }

        public string Address =>
            addressInput != null && !string.IsNullOrWhiteSpace(addressInput.text)
                ? addressInput.text.Trim()
                : (bootstrap != null && bootstrap.Config != null ? bootstrap.Config.DefaultAddress : "127.0.0.1");

        // ---- presentation ----

        private void Refresh()
        {
            var manager = Manager;
            bool listening = manager != null && manager.IsListening;
            bool connected = manager != null && manager.IsConnectedClient;

            if (statusText != null)
            {
                if (!listening)
                {
                    statusText.text = "Not connected";
                    statusText.color = new Color(0.85f, 0.85f, 0.85f);
                }
                else if (manager.IsServer)
                {
                    statusText.text = $"Hosting on port {Port} ({manager.ConnectedClientsIds.Count} player(s))";
                    statusText.color = new Color(0.55f, 0.9f, 0.55f);
                }
                else if (connected)
                {
                    statusText.text = $"Connected as client {manager.LocalClientId}";
                    statusText.color = new Color(0.55f, 0.85f, 1f);
                }
                else
                {
                    statusText.text = "Connecting...";
                    statusText.color = new Color(1f, 0.85f, 0.4f);
                }
            }

            if (playerListText != null)
            {
                _builder.Clear();
                if (listening)
                {
                    foreach (var id in manager.ConnectedClientsIds)
                    {
                        _builder.Append("player ").Append(id);
                        if (id == manager.LocalClientId) _builder.Append("  (you)");
                        if (manager.IsServer && id == NetworkManager.ServerClientId) _builder.Append("  [host]");
                        _builder.Append('\n');
                    }
                }
                playerListText.text = _builder.ToString();
            }

            if (reasonText != null)
            {
                string reason = listening ? null : SafeReason(manager);
                if (!string.IsNullOrEmpty(reason) && reason != _lastReason)
                {
                    _lastReason = reason;
                    reasonText.text = "Refused: " + reason;
                    MPLog.Warn("SESSION_REFUSED", ("reason", reason));
                }
                else if (string.IsNullOrEmpty(reason))
                {
                    reasonText.text = string.Empty;
                }
            }

            if (hostButton != null) hostButton.interactable = !listening;
            if (joinButton != null) joinButton.interactable = !listening;
            if (leaveButton != null) leaveButton.interactable = listening;
            if (addressInput != null) addressInput.interactable = !listening;
        }

        private ushort Port => bootstrap != null && bootstrap.Config != null ? bootstrap.Config.Port : (ushort)7777;

        private static string SafeReason(NetworkManager manager)
        {
            if (manager == null) return null;
            try
            {
                return manager.DisconnectReason;
            }
            catch
            {
                return null;
            }
        }

        private void ClearReason()
        {
            _lastReason = null;
            if (reasonText != null) reasonText.text = string.Empty;
        }
    }
}
